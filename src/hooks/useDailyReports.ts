/**
 * Kuro Daily Reports & Work Summaries Hook
 *
 * Scope: Phase 10 Milestone 5 (Step 10.6)
 *
 * Responsibilities:
 * 1. Loads and manages daily reports for the authenticated user from Supabase and IndexedDB.
 * 2. Provides idempotent report generation and refreshing for selected dates.
 * 3. Enforces user preferences: auto_reports_enabled, daily_report_time, telemetry_retention_days.
 * 4. Strictly respects privacy defaults: auto-reports disabled by default; opt-in foreground generation.
 * 5. Handles offline caching and syncs via outbox when connectivity returns.
 * 6. Isolated multi-tenant boundaries: purges user report state on account switch or logout.
 */

import { useState, useEffect, useCallback, useRef, useMemo } from 'react';
import type { DailyReport, TimeEntry, TimeEntryPause, TimeEntryIdle, Task, Project } from '../types';
import type { ClientWorkSession } from '../lib/adapters';
import type { OutboxOperation } from '../types/sync';
import {
  dailyReportRowToDailyReport,
  dailyReportToInsertPayload,
  taskRowToTask,
  timeEntryRowToTimeEntry,
  timeEntryPauseRowToPause,
  timeEntryIdleRowToIdle,
} from '../lib/adapters';
import {
  calculateDailyReport,
  formatYMD,
  resolveReportingTimeZone,
  getDayBoundaries,
} from '../lib/reportCalculations';
import { useAuth } from '../context/useAuth';
import { useUserPreferences } from './useUserPreferences';
import { supabase } from '../lib/supabase';
import {
  getOfflineCacheItem,
  setOfflineCacheItem,
  enqueueOutboxOperation,
  getOutboxOperationsForScope,
} from '../lib/offlineDb';
import { processOutbox } from '../lib/syncEngine';
import { getProvider, getSavedProviderId } from '../lib/ai/providerRegistry';
import { generateAiDailySummary } from '../lib/ai/dailySummary';

const DEMO_REPORTS_KEY = 'kuro_demo_daily_reports';

export interface UseDailyReportsContextData {
  timeEntries?: TimeEntry[];
  pauses?: TimeEntryPause[];
  idles?: TimeEntryIdle[];
  tasks?: Task[];
  projects?: Project[];
  legacySessions?: ClientWorkSession[];
}

export interface UseDailyReportsReturn {
  reports: DailyReport[];
  currentReport: DailyReport | null;
  loading: boolean;
  generating: boolean;
  error: string | null;
  hasPendingSync: boolean;
  generateReport: (dateStr: string, forceAi?: boolean) => Promise<DailyReport | null>;
  refreshReport: (dateStr: string) => Promise<DailyReport | null>;
  deleteReport: (id: string) => Promise<boolean>;
  retry: () => void;
}

export function useDailyReports(
  selectedDate?: string,
  contextData?: UseDailyReportsContextData
): UseDailyReportsReturn {
  const { user } = useAuth();
  const { preferences } = useUserPreferences();

  const [reports, setReports] = useState<DailyReport[]>([]);
  const [outboxOps, setOutboxOps] = useState<OutboxOperation[]>([]);
  const [loading, setLoading] = useState<boolean>(true);
  const [generating, setGenerating] = useState<boolean>(false);
  const [error, setError] = useState<string | null>(null);
  const [dbUserId, setDbUserId] = useState<string | null>(null);
  const [defaultDate] = useState<string>(() => formatYMD(new Date()));

  const activeDate = selectedDate || defaultDate;
  const autoGeneratedDateRef = useRef<string | null>(null);
  const sequenceRef = useRef<number>(0);

  // ---------------------------------------------------------------------------
  // 1. User Account Switching & Isolation Guard
  // ---------------------------------------------------------------------------
  useEffect(() => {
    const currentUserId = user?.id || null;
    if (dbUserId !== currentUserId) {
      queueMicrotask(() => {
        setReports([]);
        setOutboxOps([]);
        setError(null);
        setLoading(true);
        setDbUserId(currentUserId);
        autoGeneratedDateRef.current = null;
      });
    }
  }, [user, dbUserId]);

  // ---------------------------------------------------------------------------
  // 2. Fetch and Reconcile Reports (IndexedDB + Supabase)
  // ---------------------------------------------------------------------------
  const fetchReports = useCallback(async (userId: string) => {
    const currentSeq = ++sequenceRef.current;
    setError(null);

    // 1. Instant local IndexedDB load
    try {
      const cached = await getOfflineCacheItem<DailyReport[]>(userId, 'daily_reports_list');
      if (cached && currentSeq === sequenceRef.current) {
        setReports(cached);
        setLoading(false);
      }
    } catch {
      // Graceful fallback
    }

    if (!supabase) return;

    // 2. Remote fetch from Supabase
    try {
      const { data: rows, error: fetchErr } = await supabase
        .from('daily_reports')
        .select('*')
        .eq('user_id', userId)
        .order('report_date', { ascending: false });

      if (fetchErr) throw fetchErr;

      let remoteReports: DailyReport[] = rows ? rows.map(dailyReportRowToDailyReport) : [];

      // 3. Reconcile with pending local Outbox operations
      try {
        const ops = await getOutboxOperationsForScope(userId);
        if (currentSeq === sequenceRef.current) {
          setOutboxOps(ops);
        }
        const reportOps = ops.filter((op) => op.entityType === 'daily_report');

        for (const op of reportOps) {
          if (op.action === 'create') {
            const opReport = op.payload as unknown as DailyReport;
            const existingIdx = remoteReports.findIndex((r) => r.reportDate === opReport.reportDate);
            if (existingIdx >= 0) {
              remoteReports[existingIdx] = { ...remoteReports[existingIdx], ...opReport, hasPendingSync: true };
            } else {
              remoteReports.unshift({ ...opReport, hasPendingSync: true });
            }
          } else if (op.action === 'delete') {
            remoteReports = remoteReports.filter((r) => r.id !== op.entityId);
          }
        }
      } catch {
        // Outbox reconciliation fallback
      }

      // Sort by report_date descending
      remoteReports.sort((a, b) => b.reportDate.localeCompare(a.reportDate));

      if (currentSeq === sequenceRef.current) {
        setReports(remoteReports);
        setLoading(false);
        void setOfflineCacheItem(userId, 'daily_reports_list', remoteReports);
      }
    } catch (err) {
      if (currentSeq === sequenceRef.current) {
        console.warn('[Kuro Reports] Remote fetch error, staying with local cache:', err);
        setLoading(false);
      }
    }
  }, []);

  // Load reports effect
  useEffect(() => {
    if (!user) {
      queueMicrotask(() => {
        try {
          const demoData = localStorage.getItem(DEMO_REPORTS_KEY);
          if (demoData) {
            setReports(JSON.parse(demoData));
          }
        } catch {}
        setLoading(false);
      });
      return;
    }

    const uid = user.id;
    queueMicrotask(() => {
      void fetchReports(uid);
    });
  }, [user, fetchReports]);

  // ---------------------------------------------------------------------------
  // 3. Derive Current Selected Report (or synthesize live preview)
  // ---------------------------------------------------------------------------
  const currentReport = useMemo(() => {
    // 1. Look for existing saved report for activeDate
    const existing = reports.find((r) => r.reportDate === activeDate);
    if (existing) {
      return existing;
    }

    // 2. Synthesize live provisional report from context data
    if (contextData) {
      const provisional = calculateDailyReport({
        targetDate: activeDate,
        userId: user?.id || 'demo',
        timeEntries: contextData.timeEntries || [],
        pauses: contextData.pauses || [],
        idles: contextData.idles || [],
        tasks: contextData.tasks || [],
        projects: contextData.projects || [],
        legacySessions: contextData.legacySessions || [],
        activityTrackingEnabled: preferences.activityTrackingEnabled,
        pendingOutboxOps: outboxOps,
        timeZone: resolveReportingTimeZone(),
      });
      return provisional;
    }

    return null;
  }, [reports, activeDate, contextData, user, preferences.activityTrackingEnabled, outboxOps]);

  const hasPendingSync = useMemo(() => {
    if (!currentReport) return false;
    return Boolean(currentReport.hasPendingSync);
  }, [currentReport]);

  // ---------------------------------------------------------------------------
  // 4. Generate or Refresh Daily Report
  // ---------------------------------------------------------------------------
  const generateReport = useCallback(
    async (dateStr: string, forceAi = false): Promise<DailyReport | null> => {
      setGenerating(true);
      setError(null);

      try {
        const resolvedTz = resolveReportingTimeZone();
        const { startIso, endIso } = getDayBoundaries(dateStr, resolvedTz);
        const pendingOps = user ? await getOutboxOperationsForScope(user.id) : [];

        let effectiveTimeEntries = contextData?.timeEntries || [];
        let effectivePauses = contextData?.pauses || [];
        let effectiveIdles = contextData?.idles || [];
        let effectiveTasks = contextData?.tasks || [];

        // Remote fetch for date boundaries if authenticated
        if (user && supabase) {
          try {
            const { data: entryRows, error: entryErr } = await supabase
              .from('time_entries')
              .select('*')
              .eq('user_id', user.id)
              .lt('started_at', endIso)
              .or(`ended_at.is.null,ended_at.gt.${startIso}`);

            if (!entryErr && entryRows && entryRows.length > 0) {
              const fetchedEntries = entryRows.map(timeEntryRowToTimeEntry);
              const entryMap = new Map<string, TimeEntry>();
              for (const e of fetchedEntries) {
                entryMap.set(e.id, e);
              }
              for (const e of effectiveTimeEntries) {
                if (!entryMap.has(e.id)) {
                  entryMap.set(e.id, e);
                }
              }
              effectiveTimeEntries = Array.from(entryMap.values());

              const entryIds = effectiveTimeEntries.map((e) => e.id);
              if (entryIds.length > 0) {
                const [pausesRes, idlesRes] = await Promise.all([
                  supabase.from('time_entry_pauses').select('*').in('time_entry_id', entryIds),
                  supabase.from('time_entry_idles').select('*').in('time_entry_id', entryIds),
                ]);

                if (pausesRes.data) {
                  const fetchedPauses = pausesRes.data.map(timeEntryPauseRowToPause);
                  const pauseMap = new Map<string, TimeEntryPause>();
                  for (const p of fetchedPauses) pauseMap.set(p.id, p);
                  for (const p of effectivePauses) if (!pauseMap.has(p.id)) pauseMap.set(p.id, p);
                  effectivePauses = Array.from(pauseMap.values());
                }

                if (idlesRes.data) {
                  const fetchedIdles = idlesRes.data.map(timeEntryIdleRowToIdle);
                  const idleMap = new Map<string, TimeEntryIdle>();
                  for (const i of fetchedIdles) idleMap.set(i.id, i);
                  for (const i of effectiveIdles) if (!idleMap.has(i.id)) idleMap.set(i.id, i);
                  effectiveIdles = Array.from(idleMap.values());
                }
              }
            }
          } catch (err) {
            console.warn('[Kuro Reports] Remote fetch for date boundaries failed:', err);
          }

          if (effectiveTasks.length === 0) {
            try {
              const { data: taskRows } = await supabase
                .from('tasks')
                .select('*')
                .eq('user_id', user.id);
              if (taskRows) {
                effectiveTasks = taskRows.map(taskRowToTask);
              }
            } catch {}
          }
        }

        // Calculate report metrics from normalized timer context
        const generated = calculateDailyReport({
          targetDate: dateStr,
          userId: user?.id || 'demo',
          timeEntries: effectiveTimeEntries,
          pauses: effectivePauses,
          idles: effectiveIdles,
          tasks: effectiveTasks,
          projects: contextData?.projects || [],
          legacySessions: contextData?.legacySessions || [],
          activityTrackingEnabled: preferences.activityTrackingEnabled,
          pendingOutboxOps: pendingOps,
          timeZone: resolvedTz,
        });

        // Optional local AI enhancement (strictly local / zero-cloud)
        if (forceAi) {
          try {
            const providerId = getSavedProviderId();
            const provider = getProvider(providerId);
            const aiSummary = await generateAiDailySummary(
              {
                date: dateStr,
                displayDate: generated.reportDate,
                totalFocusMinutes: Math.round(generated.totalFocusSeconds / 60),
                totalSessionsCount: generated.sessionCount,
                projectBreakdown: generated.projectBreakdown.map((p) => ({
                  project: p.project,
                  minutes: p.minutes,
                  sessionCount: p.sessionCount,
                  ides: [],
                })),
                ideBreakdown: [],
                completedTasks: (contextData?.tasks || []).filter((t) => t.completed),
                pendingTasks: (contextData?.tasks || []).filter((t) => !t.completed),
                hasIncompleteData: false,
                rawSessions: [],
              },
              provider
            );

            if (aiSummary?.narrative) {
              generated.aiNarrative = aiSummary.narrative;
            }
            if (aiSummary?.recommendations && aiSummary.recommendations.length > 0) {
              generated.actionableSuggestions = aiSummary.recommendations;
            }
          } catch {
            // Local AI failed or aborted; deterministic narrative already present in generated
          }
        }

        // Unauthenticated demo mode
        if (!user) {
          const nextReports = [generated, ...reports.filter((r) => r.reportDate !== dateStr)];
          setReports(nextReports);
          try {
            localStorage.setItem(DEMO_REPORTS_KEY, JSON.stringify(nextReports));
          } catch {}
          return generated;
        }

        // Authenticated mode: optimistic state + IndexedDB cache
        generated.hasPendingSync = true;
        const nextReports = [generated, ...reports.filter((r) => r.reportDate !== dateStr)];
        nextReports.sort((a, b) => b.reportDate.localeCompare(a.reportDate));
        setReports(nextReports);
        void setOfflineCacheItem(user.id, 'daily_reports_list', nextReports);

        // Enqueue outbox operation for public.daily_reports (idempotent upsert on user_id,report_date)
        const insertPayload = dailyReportToInsertPayload(generated, user.id);
        await enqueueOutboxOperation({
          id: crypto.randomUUID(),
          scope: user.id,
          entityType: 'daily_report',
          entityId: generated.id,
          action: 'create',
          payload: insertPayload,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
          status: 'pending',
          retryCount: 0,
          sequenceNumber: 1,
        });

        // Trigger processing
        void processOutbox(user.id).then(() => {
          // Re-fetch outbox state to clear pending indicator
          void getOutboxOperationsForScope(user.id).then((freshOps) => {
            setOutboxOps(freshOps);
            const stillPending = freshOps.some(
              (o) => o.entityType === 'daily_report' && o.entityId === generated.id && o.status === 'pending'
            );
            if (!stillPending) {
              setReports((prev) =>
                prev.map((r) => (r.id === generated.id ? { ...r, hasPendingSync: false } : r))
              );
            }
          });
        });

        return generated;
      } catch (err: unknown) {
        const msg = err instanceof Error ? err.message : 'Failed to generate daily report';
        setError(msg);
        return null;
      } finally {
        setGenerating(false);
      }
    },
    [user, reports, contextData, preferences.activityTrackingEnabled]
  );

  const refreshReport = useCallback(
    async (dateStr: string): Promise<DailyReport | null> => {
      return generateReport(dateStr, false);
    },
    [generateReport]
  );

  // ---------------------------------------------------------------------------
  // 5. Delete Daily Report
  // ---------------------------------------------------------------------------
  const deleteReport = useCallback(
    async (id: string): Promise<boolean> => {
      const target = reports.find((r) => r.id === id);
      if (!target) return false;

      const nextReports = reports.filter((r) => r.id !== id);
      setReports(nextReports);

      if (!user) {
        try {
          localStorage.setItem(DEMO_REPORTS_KEY, JSON.stringify(nextReports));
        } catch {}
        return true;
      }

      void setOfflineCacheItem(user.id, 'daily_reports_list', nextReports);

      await enqueueOutboxOperation({
        id: crypto.randomUUID(),
        scope: user.id,
        entityType: 'daily_report',
        entityId: id,
        action: 'delete',
        payload: { id },
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
        status: 'pending',
        retryCount: 0,
      });

      void processOutbox(user.id);
      return true;
    },
    [user, reports]
  );

  // ---------------------------------------------------------------------------
  // 6. Automation & Privacy Verification (Foreground-Triggered Schedule)
  // ---------------------------------------------------------------------------
  useEffect(() => {
    // If auto_reports_enabled is FALSE (the default!), never generate automatically!
    if (!user || !preferences.autoReportsEnabled) return;

    const checkAutoReport = () => {
      const now = new Date();
      const todayStr = formatYMD(now);

      // Prevent duplicate generation for the same date in this session
      if (autoGeneratedDateRef.current === todayStr) return;

      const [targetHour, targetMin] = (preferences.dailyReportTime || '18:00').split(':').map(Number);
      const currentMinutes = now.getHours() * 60 + now.getMinutes();
      const targetMinutes = (targetHour || 18) * 60 + (targetMin || 0);

      if (currentMinutes >= targetMinutes) {
        const existingToday = reports.find((r) => r.reportDate === todayStr);
        if (!existingToday) {
          autoGeneratedDateRef.current = todayStr;
          void generateReport(todayStr, false);
        }
      }
    };

    checkAutoReport();
    const timer = setInterval(checkAutoReport, 60000);
    return () => clearInterval(timer);
  }, [user, preferences.autoReportsEnabled, preferences.dailyReportTime, reports, generateReport]);

  const retry = useCallback(() => {
    if (user) {
      void fetchReports(user.id);
    }
  }, [user, fetchReports]);

  return {
    reports,
    currentReport,
    loading,
    generating,
    error,
    hasPendingSync,
    generateReport,
    refreshReport,
    deleteReport,
    retry,
  };
}
